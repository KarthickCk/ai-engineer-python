# Script 2 — Variables (boxes that store values).
# Run it with:  python3 02_variables.py

name = "Karthick Ji"        # a string (text)
age = 34             # an integer (whole number)
height = 6.1          # a float (decimal number)
is_learning = False      # a boolean (True/False)

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Currently learning:", is_learning)

# f-strings: the modern way to put variables inside text.
print(f"{name} is {age} years old")
