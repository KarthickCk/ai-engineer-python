# Script 3 — Numbers and math.
# Run it with:  python3 03_numbers.py

a = 10
b = 3

print("Add:      ", a + b)   # 13
print("Subtract: ", a - b)   # 7
print("Multiply: ", a * b)   # 30
print("Divide:   ", a / b)   # 3.333...
print("Floor div:", a // b)  # 3  (drops the decimal)
print("Remainder:", a % b)   # 1  (the leftover)
print("Power:    ", a ** b)  # 1000  (10 to the power 3)

